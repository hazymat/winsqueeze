# Builds ui/src/parts/vfdFont.ts: the Transporter big line's dot font, every glyph drawn on the display's dot grid (SPEC.md › Transporter mode)
# Glyphs come from Liberation Sans (SIL Open Font License 1.1) rasterised without smoothing at 22 px, with 1-dot strokes widened to 2 like the unit's own font.
# Usage: python3 tools/vfd_font.py /path/to/LiberationSans-Regular.ttf
import json, sys
from PIL import Image, ImageDraw, ImageFont
font_path = sys.argv[1] if len(sys.argv) > 1 else '/usr/share/fonts/truetype/liberation/LiberationSans-Regular.ttf'
font = ImageFont.truetype(font_path, 22)
baseline, top_row, bottom_row = 27, 8, 31  # display rows: the small line uses 1-7, the big line 8-31
ranges = [(0x20, 0x7E), (0xA0, 0x17F), (0x400, 0x45F), (0x490, 0x491)] + [(code, code) for code in (0x2018, 0x2019, 0x201C, 0x201D, 0x2013, 0x2014, 0x2026, 0x2022, 0x20AC)]
def glyph_columns(character):
    room = int(font.getlength(character)) + 8
    image = Image.new('1', (room, 40), 0); draw = ImageDraw.Draw(image); draw.fontmode = '1'; draw.text((2, baseline), character, font=font, fill=1, anchor='ls')
    rows = [[image.getpixel((x, y)) for x in range(room)] for y in range(40)]
    for row in rows:  # every stroke 2 dots wide: a lone dot gets a neighbour on its right
        source = row[:]
        for x in range(1, room - 1):
            if source[x] and not source[x - 1] and not source[x + 1]: row[x + 1] = 1
    used = [x for x in range(room) if any(rows[y][x] for y in range(top_row, bottom_row + 1))]
    if not used: return None
    return [sum(1 << (y - top_row) for y in range(top_row, bottom_row + 1) if rows[y][x]) for x in range(used[0], used[-1] + 1)]
glyphs = {}
for first, last in ranges:
    for code in range(first, last + 1):
        character = chr(code)
        if code == 0x20 or code == 0xA0: continue
        if not font.getmask(character).getbbox(): continue
        columns = glyph_columns(character)
        if columns: glyphs[character] = ','.join(format(column, 'x') for column in columns)
lines = ['// Generated by tools/vfd_font.py: do not edit. Glyph shapes from Liberation Sans, SIL Open Font License 1.1 (https://openfontlicense.org)',
         '// Each glyph is its columns left to right, each column a hex bitmask of display rows 8 (bit 0) to 31',
         f'export const vfdTop = {top_row}',
         'const packed: Record<string, string> = ' + json.dumps(glyphs, ensure_ascii=False, separators=(',', ':')),
         "export const vfdGlyphs: Record<string, number[]> = Object.fromEntries(Object.entries(packed).map(([character, columns]) => [character, columns.split(',').map(column => parseInt(column, 16))]))"]
open('ui/src/parts/vfdFont.ts', 'w', encoding='utf-8').write('\n'.join(lines) + '\n')
print(len(glyphs), 'glyphs')
