# Builds ui/src/parts/lyrionVu.ts from vendor/lyrion-graphics/vumeter.bmp: the Transporter's own analog VU meter (vendor/lyrion-graphics/README.md)
# The strip is 48 frames of 160 x 32 dots in four grey levels, one frame per needle position; stored as the face without a needle plus each frame's needle dots
import base64, json, struct
from collections import Counter
source, target, frame_width, frame_count = 'vendor/lyrion-graphics/vumeter.bmp', 'ui/src/parts/lyrionVu.ts', 160, 48
data = open(source, 'rb').read()
pixel_offset, = struct.unpack_from('<i', data, 10); header_size, width, height, _, bits = struct.unpack_from('<iiiHH', data, 14)
assert data[:2] == b'BM' and bits == 8 and width == frame_width * frame_count and abs(height) == 32
palette = 14 + header_size
colours = sorted({data[pixel_offset + row * width + column] for row in range(32) for column in range(width)}, key = lambda entry: sum(data[palette + entry * 4:palette + entry * 4 + 3]))
assert len(colours) <= 4
level_of = {entry: rank for rank, entry in enumerate(colours)}
def level(column, row): return level_of[data[pixel_offset + ((31 - row) if height > 0 else row) * width + column]]
frames = [[[level(frame * frame_width + column, row) for column in range(frame_width)] for row in range(32)] for frame in range(frame_count)]
face = [[Counter(frames[frame][row][column] for frame in range(frame_count)).most_common(1)[0][0] for column in range(frame_width)] for row in range(32)]
face_bytes = bytes(sum(face[row][column + part] << (6 - part * 2) for part in range(4)) for row in range(32) for column in range(0, frame_width, 4))
needles = [''.join(f'{column:02x}{row:02x}{frames[frame][row][column]}' for row in range(32) for column in range(frame_width) if frames[frame][row][column] != face[row][column]) for frame in range(frame_count)]
open(target, 'w', newline = '\n').write('\n'.join([
  '// Generated by tools/lyrion_vu.py from vendor/lyrion-graphics/vumeter.bmp (Lyrion / Slim Devices): do not edit',
  '// face: 160 x 32 grey levels 0-3, four dots a byte; needles: per frame, each changed dot as 2 hex column + 2 hex row + level',
  f"export const lyrionVuFace = Uint8Array.from(atob('{base64.b64encode(face_bytes).decode()}'), character => character.charCodeAt(0))",
  f'export const lyrionVuNeedles: string[] = {json.dumps(needles)}', '']))
print(target, len(face_bytes), sum(map(len, needles)))
