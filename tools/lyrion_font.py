# Builds ui/src/parts/lyrionFont.ts from vendor/lyrion-graphics/standard.2.font.bmp: the Transporter's own big-line font (vendor/lyrion-graphics/README.md)
# Read the way Lyrion reads it (Slim::Display::Lib::Fonts::parseFont): a dark dot on the bottom row separates characters, the columns between are one
# character each, in Windows-1252 order; character 0 is the gap put between letters (none if it has dots)
import json, struct
source, target = 'vendor/lyrion-graphics/standard.2.font.bmp', 'ui/src/parts/lyrionFont.ts'
data = open(source, 'rb').read()
pixel_offset, = struct.unpack_from('<i', data, 10); header_size, width, height = struct.unpack_from('<iii', data, 14)
assert data[:2] == b'BM' and struct.unpack_from('<H', data, 28)[0] == 1 and abs(height) == 33
palette = 14 + header_size
brightness = lambda entry: sum(data[palette + entry * 4:palette + entry * 4 + 3])
ink_bit = 1 if brightness(1) < brightness(0) else 0
stride, rows, top_row = (width + 31) // 32 * 4, abs(height), 8
def ink(column, row):
    file_row = rows - 1 - row if height > 0 else row
    return (data[pixel_offset + file_row * stride + column // 8] >> (7 - column % 8) & 1) == ink_bit
characters, column = [], 0
while column < width:
    if ink(column, rows - 1): column += 1; continue
    character = []
    while column < width and not ink(column, rows - 1):
        character.append(sum(1 << (row - top_row) for row in range(top_row, 32) if ink(column, row))); column += 1
    characters.append(character)
glyphs = {}
for code in range(33, 256):
    if code in (127, 160) or not any(characters[code]): continue
    try: character = bytes([code]).decode('cp1252')
    except UnicodeDecodeError: continue
    glyphs[character] = ','.join(format(mask, 'x') for mask in characters[code])
gap = 0 if any(characters[0]) else len(characters[0])
lines = ['// Generated by tools/lyrion_font.py from vendor/lyrion-graphics/standard.2.font.bmp (Lyrion / Slim Devices): do not edit',
         '// Each glyph is its columns left to right, each column a hex bitmask of display rows 8 (bit 0) to 31',
         f'export const lyrionFont = {{ top: {top_row}, gap: {gap}, space: {len(characters[32])}, glyphs: {{}} as Record<string, number[]> }}',
         'const packed: Record<string, string> = ' + json.dumps(glyphs, ensure_ascii=False, separators=(',', ':')),
         "for (const [character, columns] of Object.entries(packed)) lyrionFont.glyphs[character] = columns.split(',').map(column => parseInt(column, 16))"]
open(target, 'w', encoding='utf-8').write('\n'.join(lines) + '\n')
print(len(glyphs), 'glyphs, gap', gap)
